def _extract_json_object(text: str, label: str) -> dict[str, Any]:
    cleaned = text.strip()
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
        cleaned = re.sub(r"\s*```$", "", cleaned)
    try:
        payload = json.loads(cleaned)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", cleaned, re.DOTALL)
        if not match:
            raise ProjectRuntimeError(f"{label} did not contain JSON.") from None
        try:
            payload = json.loads(match.group(0))
        except json.JSONDecodeError as exc:
            raise ProjectRuntimeError(f"{label} JSON was malformed.") from exc
    if not isinstance(payload, dict):
        raise ProjectRuntimeError(f"{label} JSON must be an object.")
    return payload


def _slugify(value: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", value.lower()).strip("-")
    return slug[:48].strip("-")


def _tool_name(value: str) -> str:
    name = re.sub(r"[^a-zA-Z0-9_]+", "_", value.lower()).strip("_")
    if not name:
        name = "run_specialist"
    if not name[0].isalpha():
        name = f"tool_{name}"
    return name[:64]


def _clean_text(value: object) -> str:
    return str(value or "").strip()


def _clean_complexity(value: object) -> str:
    text = _clean_text(value).lower()
    return text if text in {"small", "medium", "large"} else "medium"


def _clean_int(value: object, default: int = 0) -> int:
    try:
        number = int(value)
    except (TypeError, ValueError):
        return default
    return max(0, number)


def _clean_dependency_names(value: object, name_map: dict[str, str]) -> list[str]:
    if not isinstance(value, list):
        return []
    dependencies: list[str] = []
    for item in value:
        dependency = _clean_text(item)
        if not dependency:
            continue
        dependencies.append(name_map.get(dependency.lower(), dependency))
    return _dedupe_dependencies(dependencies, self_name="")


def _dedupe_dependencies(dependencies: list[str], self_name: str) -> list[str]:
    clean: list[str] = []
    seen: set[str] = set()
    self_key = self_name.lower()
    for dependency in dependencies:
        name = _clean_text(dependency)
        key = name.lower()
        if not name or key == self_key or key in seen:
            continue
        clean.append(name)
        seen.add(key)
    return clean


def _unique_agent_name(name: str, used_names: set[str]) -> str:
    base = re.sub(r"\s+", " ", name).strip() or "Specialist"
    if base.lower() not in used_names:
        return base[:60]
    index = 2
    while f"{base} {index}".lower() in used_names:
        index += 1
    return f"{base} {index}"[:60]

