def _run_planner_llama_agent(
    name: str,
    instructions: str,
    input_text: str,
    max_tokens: int,
    tools: list[ToolFunction] | None = None,
    timeout: int = 120,
) -> str:
    try:
        return _run_llama_agent(name, instructions, input_text, max_tokens, tools, timeout)
    except ProjectRuntimeError as exc:
        if tools and "did not produce output" in str(exc):
            retry_instructions = (
                f"{instructions} "
                "If a context tool is unavailable or does not lead to a final response, continue from the provided context "
                "and return the required JSON object now. Do not call tools in this retry."
            )
            return _run_llama_agent(name, retry_instructions, input_text, max_tokens, None, timeout)
        raise


def _run_sub_orchestrator_dag(
    user_prompt: str,
    plan: WorkflowPlan,
    sub_orchestrator_agents: list[Agent],
    workspace: ProjectWorkspace,
    orchestrator: Agent,
    emit: Emitter,
    used_names: set[str],
) -> list[tuple[PlannedSubOrchestrator, Agent, list[PlannedAgent]]]:
    if not sub_orchestrator_agents:
        return []

    raw_outputs: dict[str, str] = {}
    with ThreadPoolExecutor(max_workers=len(sub_orchestrator_agents)) as executor:
        futures = {}
        for planned_sub_orchestrator, sub_orchestrator in zip(plan.sub_orchestrators, sub_orchestrator_agents):
            _emit_handoff(orchestrator, sub_orchestrator, f"Plan specialists for domain: {planned_sub_orchestrator.domain}", emit)
            _start_agent(sub_orchestrator, emit)
            future = executor.submit(
                _run_planner_llama_agent,
                sub_orchestrator.name,
                _sub_orchestrator_instructions(planned_sub_orchestrator, plan),
                _sub_orchestrator_input(user_prompt, plan, planned_sub_orchestrator, workspace),
                2400,
                [_relationship_graph_tool(workspace)] if workspace.reuse_existing else None,
                SUB_ORCHESTRATOR_TIMEOUT_SECONDS,
            )
            futures[future] = sub_orchestrator

        for future in as_completed(futures):
            sub_orchestrator = futures[future]
            try:
                raw_outputs[sub_orchestrator.name] = future.result()
            except Exception:
                sub_orchestrator.status = "failed"
                sub_orchestrator.finished_at = now_iso()
                raise

    planned_results: list[tuple[PlannedSubOrchestrator, Agent, list[PlannedAgent]]] = []
    for planned_sub_orchestrator, sub_orchestrator in zip(plan.sub_orchestrators, sub_orchestrator_agents):
        planned_specialists = parse_sub_orchestrator_plan(
            raw_outputs[sub_orchestrator.name],
            planned_sub_orchestrator.name,
            used_names,
        )
        planned_results.append((planned_sub_orchestrator, sub_orchestrator, planned_specialists))
    return planned_results


def _run_specialist_dag(
    user_prompt: str,
    plan: WorkflowPlan,
    specialist_agents: list[Agent],
    specialist_outputs: list[str],
    workspace: ProjectWorkspace,
    orchestrator: Agent,
    emit: Emitter,
    relationship_agent: Agent | None = None,
    run: Run | None = None,
) -> str:
    if not specialist_agents:
        return "No specialist agents were required."

    levels = _agent_execution_levels(specialist_agents)
    agent_by_name = {agent.name: agent for agent in specialist_agents}
    emit_lock = Lock()

    def thread_safe_emit(message: Message, agent: Agent | None = None) -> None:
        with emit_lock:
            emit(message, agent)

    summaries: list[str] = []
    for level_index, level in enumerate(levels, start=1):
        level_names = ", ".join(agent.name for agent in level)
        emit(
            Message(
                sender="Orchestrator",
                recipient="all",
                kind="system",
                content=f"Running DAG level {level_index} in parallel: {level_names}",
            )
        )
        outputs_before_level = list(specialist_outputs)

        def run_one(agent: Agent) -> list[str]:
            local_outputs = list(outputs_before_level)
            before_count = len(local_outputs)
            sender = _dependency_sender(agent, agent_by_name, orchestrator)
            _run_specialist_agent(user_prompt, plan, agent, local_outputs, workspace, sender, thread_safe_emit)
            return local_outputs[before_count:]

        with ThreadPoolExecutor(max_workers=len(level)) as executor:
            futures = {executor.submit(run_one, agent): agent for agent in level}
            level_records: list[str] = []
            for future in as_completed(futures):
                agent = futures[future]
                try:
                    level_records.extend(future.result())
                except Exception:
                    agent.status = "failed"
                    agent.finished_at = now_iso()
                    raise
            specialist_outputs.extend(level_records)
        if relationship_agent and workspace.relationship_dirty_files():
            _run_relationship_map_agent(
                workspace,
                relationship_agent,
                workspace.relationship_dirty_files(),
                run,
                emit,
                f"Refresh after specialist DAG level {level_index}.",
            )
        summaries.append(f"Level {level_index}: {level_names}")

    return "Ran specialist DAG:\n" + "\n".join(f"- {item}" for item in summaries)


def _combine_execution_summaries(early_summary: str, later_summary: str) -> str:
    if early_summary and later_summary and later_summary != "No specialist agents were required.":
        return f"Root direct specialists:\n{early_summary}\n\nSub-orchestrator specialists:\n{later_summary}"
    if early_summary:
        return early_summary
    return later_summary


def _agent_execution_levels(agents: list[Agent]) -> list[list[Agent]]:
    agent_by_name = {agent.name: agent for agent in agents}
    remaining = set(agent_by_name)
    completed: set[str] = set()
    levels: list[list[Agent]] = []

    while remaining:
        ready_names = sorted(
            name
            for name in remaining
            if all(dependency not in agent_by_name or dependency in completed for dependency in agent_by_name[name].depends_on)
        )
        if not ready_names:
            cycle = ", ".join(sorted(remaining))
            raise ProjectRuntimeError(f"Agent dependency cycle or unsatisfied dependency among: {cycle}")
        levels.append([agent_by_name[name] for name in ready_names])
        completed.update(ready_names)
        remaining.difference_update(ready_names)
    return levels


def _dependency_sender(agent: Agent, agent_by_name: dict[str, Agent], default: Agent) -> Agent:
    for dependency in reversed(agent.depends_on):
        if dependency in agent_by_name:
            return agent_by_name[dependency]
    return default


def _assign_agent_dag_layers(agents: list[Agent]) -> None:
    agent_by_name = {agent.name: agent for agent in agents}
    remaining = set(agent_by_name)
    layer_by_name: dict[str, int] = {}
    current_layer = 0

    while remaining:
        ready_names = sorted(
            name
            for name in remaining
            if all(dependency not in agent_by_name or dependency in layer_by_name for dependency in agent_by_name[name].depends_on)
        )
        if not ready_names:
            for name in sorted(remaining):
                agent_by_name[name].parallel_group = current_layer
            return
        for name in ready_names:
            agent_by_name[name].parallel_group = current_layer
            layer_by_name[name] = current_layer
        remaining.difference_update(ready_names)
        current_layer += 1


def _workspace_tools(workspace: ProjectWorkspace) -> list[ToolFunction]:
    def read_file(path: str) -> str:
        """Read a UTF-8 text file using a path relative to the project root, such as README.md or src/main.py."""
        return workspace.read_file(path)

    def search_files(query: str, max_results: int = 8) -> str:
        """Search project filenames and UTF-8 file contents, returning matching paths and short snippets."""
        try:
            limit = int(max_results)
        except (TypeError, ValueError):
            limit = 8
        return json.dumps(workspace.search_files(query, limit), indent=2)

    def relationship_graph() -> str:
        """Recommended for existing-project work: read the current direct file relationship map for context, then continue with your required final response."""
        return workspace.relationship_graph()

    def write_file(path: str, content: str) -> str:
        """Create or replace a UTF-8 text file using a project-root-relative path, such as index.html or app.js."""
        written = workspace.write_file(path, content)
        return f"Wrote {written}"

    def append_file(path: str, content: str) -> str:
        """Append UTF-8 text using a project-root-relative path; do not include generated_projects or the project folder."""
        written = workspace.append_file(path, content)
        return f"Appended to {written}"

    def list_files() -> str:
        """List files currently written inside the generated project workspace."""
        files = workspace.list_files()
        return json.dumps(files, indent=2)

    def show_changes() -> str:
        """Show files created, modified, or deleted since this run started."""
        return json.dumps(workspace.change_summary(), indent=2)

    return [read_file, search_files, relationship_graph, write_file, append_file, list_files, show_changes]


def _list_files_tool(workspace: ProjectWorkspace) -> ToolFunction:
    def list_files() -> str:
        """List files currently written inside the generated project workspace."""
        return json.dumps(workspace.list_files(), indent=2)

    return list_files


def _relationship_graph_tool(workspace: ProjectWorkspace) -> ToolFunction:
    def relationship_graph() -> str:
        """Read the current direct file relationship map for context, then continue with your required final response."""
        return workspace.relationship_graph()

    return relationship_graph


def _specialist_tools(
    user_prompt: str,
    plan: WorkflowPlan,
    specialist_agents: list[Agent],
    specialist_outputs: list[str],
    workspace: ProjectWorkspace,
    sender: Agent,
    emit: Emitter,
) -> list[ToolFunction]:
    tools: list[ToolFunction] = []

    def make_specialist_tool(specialist: Agent) -> ToolFunction:
        def run_specialist(task_brief: str = "") -> str:
            """Run one specialist coding agent and let it write files through scoped project tools."""
            if specialist.status == "done":
                return specialist.output or f"{specialist.name} already completed."
            return _run_specialist_agent(
                user_prompt,
                plan,
                specialist,
                specialist_outputs,
                workspace,
                sender,
                emit,
                task_brief,
            )

        run_specialist.__name__ = _tool_name(f"run_{specialist.name}")
        run_specialist.__doc__ = (
            f"Run {_clean_text(specialist.name)}. Purpose: {specialist.purpose}. "
            f"Task: {specialist.task}. Use this to delegate real coding work to that specialist."
        )
        return run_specialist

    for specialist in specialist_agents:
        tools.append(make_specialist_tool(specialist))
    return tools


def _run_specialist_agent(
    user_prompt: str,
    plan: WorkflowPlan,
    specialist: Agent,
    specialist_outputs: list[str],
    workspace: ProjectWorkspace,
    sender: Agent,
    emit: Emitter,
    task_brief: str = "",
) -> str:
    _emit_handoff(sender, specialist, task_brief or f"Own this subtask: {specialist.task}", emit)
    _start_agent(specialist, emit)
    raw_output = _run_llama_agent(
        specialist.name,
        _specialist_instructions(specialist, plan),
        _specialist_input(user_prompt, plan, specialist_outputs, specialist, workspace, task_brief),
        tools=_workspace_tools(workspace),
        max_tokens=4500,
        timeout=SPECIALIST_TIMEOUT_SECONDS,
    )
    files = workspace.list_files()
    changes = workspace.change_summary()
    specialist.output = _workspace_agent_summary(raw_output, files, changes)
    specialist_outputs.append(
        json.dumps(
            {
                "agent": specialist.name,
                "task": specialist.task,
                "input_format": specialist.input_format,
                "expected_output_format": specialist.expected_output_format,
                "logic": specialist.logic,
                "output": raw_output,
                "files_after_agent": files,
                "changes_after_agent": changes,
            },
            indent=2,
        )
    )
    _mark_done(None, specialist, emit)
    return specialist.output


def _run_relationship_map_agent(
    workspace: ProjectWorkspace,
    relationship_agent: Agent,
    selected_files: list[str],
    run: Run | None,
    emit: Emitter,
    reason: str,
) -> str:
    files = sorted(set(selected_files))
    if not workspace.reuse_existing:
        return ""
    _start_agent(relationship_agent, emit)
    workspace.refresh_project_documents(files)
    evidence = build_relationship_map_evidence(workspace.project_dir, files, workspace.list_files())
    if evidence.files:
        raw_output = _run_llama_agent(
            relationship_agent.name,
            _relationship_map_instructions(),
            _relationship_map_input(workspace, evidence, reason),
            max_tokens=2600,
            timeout=PLANNER_TIMEOUT_SECONDS,
        )
        update = parse_relationship_map_response(
            raw_output,
            [item.path for item in evidence.files],
            evidence.removed,
        )
    else:
        update = RelationshipMapUpdate(entries={}, removed=evidence.removed)
    context = workspace.apply_relationship_map_update(update, files)
    output = (
        f"{reason}\n"
        f"Updated relationship entries for {len(files)} selected file(s): "
        f"{', '.join(files) if files else 'none'}.\n\n"
        f"{context}"
    )
    relationship_agent.input = json.dumps(files, indent=2)
    relationship_agent.output = output
    if run is not None:
        run.relationship_summary = context
    _mark_done(run, relationship_agent, emit)
    return output


