def run_project_workflow(run: Run, emit: Emitter) -> None:
    GENERATED_ROOT.mkdir(parents=True, exist_ok=True)
    run.status = "planning"
    selected_project = _slugify(run.selected_project)
    run.project_mode = "existing" if selected_project else "new"

    orchestrator = Agent(
        name="Orchestrator",
        purpose="Design a request-specific multi-agent workflow.",
        task="Assign specialist agents and subtasks from the user's chat request.",
        input=run.prompt,
    )
    workspace: ProjectWorkspace | None = None
    repo_intake: RepoIntake | None = None
    intake_agent: Agent | None = None
    code_index_agent: Agent | None = None
    relationship_agent: Agent | None = None
    if selected_project:
        workspace = ProjectWorkspace(selected_project, reuse_existing=True)
        workspace.ensure_created()
        repo_intake = build_repo_intake(workspace.project_dir, selected_project)
        run.repo_summary = repo_intake.to_prompt_context()
        workspace.repo_intake_context = run.repo_summary
        intake_agent = Agent(
            name="Repository Intake Agent",
            purpose="Map the selected existing project before planning changes.",
            task="Scan files, manifests, docs, entrypoints, and likely verification commands.",
            input=f"Selected project: {selected_project}",
            input_format="Existing generated project folder.",
            expected_output_format="Compact repo map for brownfield planning.",
            logic="Deterministically inspect the selected folder and summarize useful project context.",
            deliverable="Repo intake summary for the Orchestrator and specialist agents.",
        )
        code_index_agent = Agent(
            name="Code Index Agent",
            purpose="Build a navigable code index for the selected project.",
            task="Index text/code files, symbols, imports, selectors, and snippets before planning.",
            input=f"Selected project: {selected_project}",
            input_format="Existing generated project folder plus repository intake summary.",
            expected_output_format="Code index summary with important files and symbols.",
            logic="Create local LlamaIndex Document entries and symbol/import summaries for coding agents.",
            deliverable="Code index summary for the Relationship Map Agent and specialists.",
            depends_on=[intake_agent.name],
        )
        relationship_agent = Agent(
            name="Relationship Map Agent",
            purpose="Build and refresh the direct file relationship map for the selected project.",
            task="Read selected project files and summarize direct file relationships for orchestration and coding agents.",
            input=f"Selected project: {selected_project}",
            input_format="List of workspace-relative files to inspect.",
            expected_output_format="Natural-language relationship map stored as LlamaIndex Document objects.",
            logic="Update only selected files' relationship entries, preserving unchanged map entries.",
            deliverable="Current direct relationship map for the Orchestrator, specialists, and builder.",
            depends_on=[code_index_agent.name],
        )
        orchestrator.depends_on = [relationship_agent.name]
        run.agents = [intake_agent, code_index_agent, relationship_agent, orchestrator]
    else:
        run.agents = [orchestrator]
    emit(
        Message(
            sender="Orchestrator",
            recipient="all",
            kind="system",
            content=(
                "Starting a LlamaIndex project-generation workflow. "
                "The orchestrator will design and coordinate specialist coding agents with scoped file tools."
            ),
        )
    )

    if intake_agent and repo_intake:
        _start_agent(intake_agent, emit)
        intake_agent.output = repo_intake.to_prompt_context()
        _mark_done(run, intake_agent, emit)
    if code_index_agent and workspace:
        _start_agent(code_index_agent, emit)
        code_index = workspace.build_code_index()
        run.code_index_summary = code_index.to_prompt_context()
        code_index_agent.output = run.code_index_summary
        _mark_done(run, code_index_agent, emit)
    if relationship_agent and workspace:
        _run_relationship_map_agent(
            workspace,
            relationship_agent,
            workspace.list_files(),
            run,
            emit,
            "Initial relationship map for the selected existing project.",
        )

    _start_agent(orchestrator, emit)
    plan_text = _run_planner_llama_agent(
        orchestrator.name,
        _orchestrator_instructions(),
        _orchestrator_input(
            run.prompt,
            selected_project,
            repo_intake,
            workspace.code_index_context if workspace else "",
        ),
        tools=[_relationship_graph_tool(workspace)] if workspace and workspace.reuse_existing else None,
        max_tokens=2600,
        timeout=PLANNER_TIMEOUT_SECONDS,
    )
    plan = parse_workflow_plan(plan_text, run.prompt)
    if workspace is None:
        workspace = ProjectWorkspace(plan.project_name)
        workspace.ensure_created()
    mode = f"Continuing existing project: {selected_project}" if selected_project else "Creating a new project from scratch"
    orchestrator.output = f"{_plan_summary(plan)}\n\n{mode}\nProject workspace: {workspace.project_dir}"
    _mark_done(run, orchestrator, emit)

    sub_orchestrator_agents = [_agent_from_sub_orchestrator(item) for item in plan.sub_orchestrators]
    specialist_agents = [_agent_from_plan(agent) for agent in plan.agents]
    for sub_orchestrator in sub_orchestrator_agents:
        sub_orchestrator.depends_on = ["Orchestrator"]
    for specialist in specialist_agents:
        specialist.depends_on = _dedupe_dependencies(["Orchestrator", *specialist.depends_on], specialist.name)
    builder = Agent(
        name="Project Builder",
        purpose="Consolidate all specialist deliverables into a complete source tree.",
        task="Generate every required project file as a JSON file manifest.",
        input=(
            f"Selected existing project: {selected_project}. File tools must receive workspace-relative paths only."
            if selected_project
            else f"Project name: {plan.project_name}. File tools must receive workspace-relative paths only."
        ),
        depends_on=[agent.name for agent in specialist_agents] or [agent.name for agent in sub_orchestrator_agents] or ["Orchestrator"],
    )
    verifier = Agent(
        name="Verification Agent",
        purpose="Materialize files and verify generated code locally.",
        task="Create the project folder, write files, list artifacts, and run safe verification.",
        input="Generated project files on disk.",
        depends_on=["Project Builder"],
    )
    reviewer = Agent(
        name="Review Agent",
        purpose="Review the generated project and report remaining gaps.",
        task="Inspect the generated files and verification result, then produce a final review.",
        input="Written files and verification output.",
        depends_on=["Verification Agent"],
    )
    intake_agents = [agent for agent in (intake_agent, code_index_agent, relationship_agent) if agent is not None]
    run.agents = [*intake_agents, orchestrator, *sub_orchestrator_agents, *specialist_agents, builder, verifier, reviewer]
    _assign_agent_dag_layers(run.agents)
    if sub_orchestrator_agents:
        emit(
            Message(
                sender="Orchestrator",
                recipient="all",
                kind="system",
                content="Assigned sub-orchestrators: " + ", ".join(agent.name for agent in sub_orchestrator_agents),
            )
        )

    used_specialist_names = {
        "orchestrator",
        "project builder",
        "verification agent",
        "review agent",
        "relationship map agent",
        *(agent.name.lower() for agent in sub_orchestrator_agents),
        *(agent.name.lower() for agent in specialist_agents),
    }
    run.status = "running"
    specialist_outputs: list[str] = []
    early_execution_summary = ""
    if sub_orchestrator_agents and specialist_agents:
        parallel_emit_lock = Lock()

        def parallel_emit(message: Message, agent: Agent | None = None) -> None:
            with parallel_emit_lock:
                emit(message, agent)

        with ThreadPoolExecutor(max_workers=2) as executor:
            sub_future = executor.submit(
                _run_sub_orchestrator_dag,
                run.prompt,
                plan,
                sub_orchestrator_agents,
                workspace,
                orchestrator,
                parallel_emit,
                used_specialist_names,
            )
            specialist_future = executor.submit(
                _run_specialist_dag,
                run.prompt,
                plan,
                specialist_agents,
                specialist_outputs,
                workspace,
                orchestrator,
                parallel_emit,
                relationship_agent,
                run,
            )
            planned_sub_orchestrator_results = sub_future.result()
            early_execution_summary = specialist_future.result()
    else:
        planned_sub_orchestrator_results = _run_sub_orchestrator_dag(
            run.prompt,
            plan,
            sub_orchestrator_agents,
            workspace,
            orchestrator,
            emit,
            used_specialist_names,
        )

    sub_orchestrator_specialists: list[Agent] = []
    for planned_sub_orchestrator, sub_orchestrator, planned_specialists in planned_sub_orchestrator_results:
        if len(specialist_agents) + len(planned_specialists) > MAX_TOTAL_SPECIALISTS:
            raise ProjectRuntimeError(
                f"Sub-orchestrators produced too many specialists: "
                f"{len(specialist_agents) + len(planned_specialists)} > {MAX_TOTAL_SPECIALISTS}."
            )
        new_specialists = [_agent_from_plan(agent) for agent in planned_specialists]
        for new_specialist in new_specialists:
            new_specialist.depends_on = _dedupe_dependencies(
                [sub_orchestrator.name, *new_specialist.depends_on],
                new_specialist.name,
            )
        specialist_agents.extend(new_specialists)
        sub_orchestrator_specialists.extend(new_specialists)
        used_specialist_names.update(agent.name.lower() for agent in new_specialists)
        sub_orchestrator.output = _sub_orchestrator_summary(planned_sub_orchestrator, planned_specialists)
        _mark_done(run, sub_orchestrator, emit)

    builder.depends_on = [agent.name for agent in specialist_agents] or [agent.name for agent in sub_orchestrator_agents] or ["Orchestrator"]
    run.agents = [*intake_agents, orchestrator, *sub_orchestrator_agents, *specialist_agents, builder, verifier, reviewer]
    _assign_agent_dag_layers(run.agents)
    emit(
        Message(
            sender="Orchestrator",
            recipient="all",
            kind="system",
            content="Assigned dynamic agents: " + ", ".join(agent.name for agent in specialist_agents),
        )
    )
    remaining_specialists = sub_orchestrator_specialists if early_execution_summary else specialist_agents
    later_execution_summary = _run_specialist_dag(
        run.prompt,
        plan,
        remaining_specialists,
        specialist_outputs,
        workspace,
        orchestrator,
        emit,
        relationship_agent,
        run,
    )
    execution_summary = _combine_execution_summaries(early_execution_summary, later_execution_summary)
    orchestrator.output = f"{orchestrator.output}\n\nDAG execution result:\n{execution_summary}"
    emit(Message(sender="Orchestrator", recipient="all", kind="agent", content=execution_summary), orchestrator)

    previous_agent = specialist_agents[-1] if specialist_agents else orchestrator
    _emit_handoff(previous_agent, builder, "Inspect the current project files, resolve gaps, and complete the project.", emit)
    _start_agent(builder, emit)
    builder.output = _run_llama_agent(
        builder.name,
        _builder_instructions(),
        _builder_input(run.prompt, plan, specialist_outputs, workspace),
        tools=_workspace_tools(workspace),
        max_tokens=7000,
        timeout=BUILDER_TIMEOUT_SECONDS,
    )
    _mark_done(run, builder, emit)
    if relationship_agent and workspace.relationship_dirty_files():
        _run_relationship_map_agent(
            workspace,
            relationship_agent,
            workspace.relationship_dirty_files(),
            run,
            emit,
            "Refresh after Project Builder changes.",
        )
    _emit_handoff(builder, verifier, "Verify the generated files from disk.", emit)

    _start_agent(verifier, emit)
    written = workspace.list_files()
    verification = workspace.verify()
    changes = workspace.change_summary()
    run.modified_files = changes
    verifier.output = _verification_report(workspace.project_dir, written, verification, changes)
    run.project_path = str(workspace.project_dir)
    run.artifacts = [
        {"name": file_path, "description": str(workspace.project_dir / file_path)}
        for file_path in written
    ]
    _mark_done(run, verifier, emit)
    _emit_handoff(verifier, reviewer, "Review the generated folder and verification output.", emit)

    _start_agent(reviewer, emit)
    reviewer.output = _run_llama_agent(
        reviewer.name,
        _reviewer_instructions(),
        (
            f"User request:\n{run.prompt}\n\n"
            f"Workflow plan:\n{_plan_summary(plan)}\n\n"
            f"Generated project folder:\n{workspace.project_dir}\n\n"
            f"Generated files:\n{json.dumps(written, indent=2)}\n\n"
            f"Changed files:\n{json.dumps(changes, indent=2)}\n\n"
            f"Verification output:\n{verification}"
        ),
        tools=[_list_files_tool(workspace), _relationship_graph_tool(workspace)],
        max_tokens=1400,
        timeout=REVIEW_TIMEOUT_SECONDS,
    )
    _mark_done(run, reviewer, emit)

    run.status = "complete"
    verb = "Updated existing project" if selected_project else "Generated project"
    file_count_text = f"Project contains {len(written)} files" if selected_project else f"Wrote {len(written)} files"
    run.summary = (
        f"{verb} at {workspace.project_dir}. "
        f"{file_count_text} for request-shaped project '{plan.project_name}'. "
        f"Changes: {_change_status(changes)}. "
        f"Verification: {_verification_status(verification)}. "
        f"Review: {reviewer.output}"
    )
    emit(Message(sender="Orchestrator", recipient="all", kind="summary", content=run.summary))


def parse_workflow_plan(text: str, prompt: str) -> WorkflowPlan:
    payload = _extract_json_object(text, "Workflow plan")
    project_name = _clean_text(payload.get("project_name")) or _slugify(prompt) or "generated-project"
    project_summary = _clean_text(payload.get("project_summary")) or prompt
    complexity = _clean_complexity(payload.get("complexity"))
    estimated_files = _clean_int(payload.get("estimated_files"), default=0)
    raw_criteria = payload.get("acceptance_criteria", [])
    acceptance_criteria = [str(item).strip() for item in raw_criteria if str(item).strip()] if isinstance(raw_criteria, list) else []
    raw_agents = payload.get("agents", [])
    raw_sub_orchestrators = payload.get("sub_orchestrators", [])
    if not isinstance(raw_agents, list):
        raise ProjectRuntimeError("Orchestrator agents must be a list.")
    if not isinstance(raw_sub_orchestrators, list):
        raise ProjectRuntimeError("Orchestrator sub_orchestrators must be a list.")
    if not raw_agents and not raw_sub_orchestrators:
        raise ProjectRuntimeError("Orchestrator did not return agents or sub_orchestrators.")
    if len(raw_agents) > MAX_DIRECT_AGENTS:
        raise ProjectRuntimeError(f"Orchestrator returned too many direct specialist agents: {len(raw_agents)} > {MAX_DIRECT_AGENTS}.")
    if len(raw_sub_orchestrators) > MAX_SUB_ORCHESTRATORS:
        raise ProjectRuntimeError(
            f"Orchestrator returned too many sub-orchestrators: {len(raw_sub_orchestrators)} > {MAX_SUB_ORCHESTRATORS}."
        )
    requires_sub_orchestrators = bool(payload.get("requires_sub_orchestrators")) or bool(raw_sub_orchestrators)

    used_names = {"orchestrator", "project builder", "verification agent", "review agent", "relationship map agent"}
    sub_orchestrators = _parse_sub_orchestrators(raw_sub_orchestrators, used_names)
    planned = _parse_planned_agents(raw_agents, "Orchestrator", used_names)

    return WorkflowPlan(
        project_name=_slugify(project_name) or "generated-project",
        project_summary=project_summary,
        complexity=complexity,
        estimated_files=estimated_files,
        requires_sub_orchestrators=requires_sub_orchestrators,
        acceptance_criteria=acceptance_criteria,
        sub_orchestrators=sub_orchestrators,
        agents=planned,
    )


def parse_sub_orchestrator_plan(
    text: str,
    sub_orchestrator_name: str,
    used_names: set[str],
) -> list[PlannedAgent]:
    payload = _extract_json_object(text, f"{sub_orchestrator_name} plan")
    raw_agents = payload.get("agents")
    if not isinstance(raw_agents, list) or not raw_agents:
        raise ProjectRuntimeError(f"{sub_orchestrator_name} did not return a non-empty agents list.")
    if len(raw_agents) > MAX_DIRECT_AGENTS:
        raise ProjectRuntimeError(
            f"{sub_orchestrator_name} returned too many specialists: {len(raw_agents)} > {MAX_DIRECT_AGENTS}."
        )
    return _parse_planned_agents(raw_agents, sub_orchestrator_name, used_names)


def _parse_planned_agents(raw_agents: list[object], label: str, used_names: set[str]) -> list[PlannedAgent]:
    name_map: dict[str, str] = {}
    unique_names: list[str] = []
    for index, raw_agent in enumerate(raw_agents, start=1):
        if not isinstance(raw_agent, dict):
            raise ProjectRuntimeError(f"{label} returned an invalid agent entry.")
        raw_name = _clean_text(raw_agent.get("name")) or f"Specialist {index}"
        unique_name = _unique_agent_name(raw_name, used_names)
        used_names.add(unique_name.lower())
        name_map[raw_name.lower()] = unique_name
        name_map[unique_name.lower()] = unique_name
        unique_names.append(unique_name)

    planned: list[PlannedAgent] = []
    for raw_agent, name in zip(raw_agents, unique_names):
        assert isinstance(raw_agent, dict)
        purpose = _clean_text(raw_agent.get("purpose")) or "Own a specialist project subtask."
        task = _clean_text(raw_agent.get("task")) or purpose
        agent_input = _clean_text(raw_agent.get("input")) or "Use the user request and previous agent outputs."
        input_format = _clean_text(raw_agent.get("input_format")) or (
            "Plain text context containing the user request, workflow plan, and prior specialist outputs."
        )
        expected_output_format = _clean_text(raw_agent.get("expected_output_format")) or (
            "Concrete file changes written through scoped project tools plus a concise summary."
        )
        logic = _clean_text(raw_agent.get("logic")) or (
            "Analyze assigned context, implement the subtask, and return concrete file contributions."
        )
        deliverable = _clean_text(raw_agent.get("deliverable")) or "Concrete implementation guidance for the builder."
        depends_on = _clean_dependency_names(raw_agent.get("depends_on"), name_map)
        planned.append(
            PlannedAgent(
                name=name,
                purpose=purpose,
                task=task,
                input=agent_input,
                input_format=input_format,
                expected_output_format=expected_output_format,
                logic=logic,
                deliverable=deliverable,
                depends_on=depends_on,
            )
        )
    return planned


def _parse_sub_orchestrators(raw_sub_orchestrators: list[object], used_names: set[str]) -> list[PlannedSubOrchestrator]:
    planned: list[PlannedSubOrchestrator] = []
    for index, raw_orchestrator in enumerate(raw_sub_orchestrators, start=1):
        if not isinstance(raw_orchestrator, dict):
            raise ProjectRuntimeError("Orchestrator returned an invalid sub-orchestrator entry.")
        domain = _clean_text(raw_orchestrator.get("domain")) or f"domain-{index}"
        name = _clean_text(raw_orchestrator.get("name")) or f"{domain.title()} Sub-Orchestrator"
        name = _unique_agent_name(name, used_names)
        used_names.add(name.lower())
        purpose = _clean_text(raw_orchestrator.get("purpose")) or f"Plan and coordinate the {domain} domain."
        task = _clean_text(raw_orchestrator.get("task")) or f"Create specialist agents for the {domain} domain."
        agent_input = _clean_text(raw_orchestrator.get("input")) or "Use the root workflow plan and user request."
        input_format = _clean_text(raw_orchestrator.get("input_format")) or (
            "Root workflow plan, domain assignment, acceptance criteria, and user request."
        )
        expected_output_format = _clean_text(raw_orchestrator.get("expected_output_format")) or (
            "JSON object with an agents list. Do not include nested sub_orchestrators."
        )
        logic = _clean_text(raw_orchestrator.get("logic")) or (
            "Split this domain into concrete implementation, testing, design, or documentation specialists."
        )
        deliverable = _clean_text(raw_orchestrator.get("deliverable")) or "Specialist agent plan for this domain."
        planned.append(
            PlannedSubOrchestrator(
                name=name,
                purpose=purpose,
                domain=domain,
                task=task,
                input=agent_input,
                input_format=input_format,
                expected_output_format=expected_output_format,
                logic=logic,
                deliverable=deliverable,
            )
        )
    return planned


def parse_project_spec(text: str, fallback_project_name: str = "generated-project") -> ProjectSpec:
    payload = _extract_json_object(text, "Implementation output")
    project_name = _clean_text(payload.get("project_name")) or fallback_project_name
    files_raw = payload.get("files")
    if not isinstance(files_raw, list) or not files_raw:
        raise ProjectRuntimeError("Project Builder did not return a non-empty files list.")
    if len(files_raw) > MAX_FILES:
        raise ProjectRuntimeError(f"Project Builder returned too many files: {len(files_raw)} > {MAX_FILES}.")

    files: list[GeneratedFile] = []
    for raw_file in files_raw:
        if not isinstance(raw_file, dict):
            raise ProjectRuntimeError("Project Builder returned an invalid file entry.")
        path = _clean_text(raw_file.get("path"))
        content = raw_file.get("content")
        if not path or not isinstance(content, str):
            raise ProjectRuntimeError("Each file entry must include path and string content.")
        if len(content) > MAX_FILE_CHARS:
            raise ProjectRuntimeError(f"{path} is too large.")
        files.append(GeneratedFile(path=path, content=content))

    return ProjectSpec(
        project_name=project_name,
        files=files,
        notes=_clean_text(payload.get("notes")),
    )


def parse_specialist_result(text: str, agent_name: str) -> SpecialistResult:
    payload = _extract_json_object(text, f"{agent_name} output")
    files_raw = payload.get("files", [])
    if not isinstance(files_raw, list):
        raise ProjectRuntimeError(f"{agent_name} output files must be a list.")
    if not files_raw:
        raise ProjectRuntimeError(f"{agent_name} did not contribute any files.")

    files: list[GeneratedFile] = []
    for raw_file in files_raw:
        if not isinstance(raw_file, dict):
            raise ProjectRuntimeError(f"{agent_name} returned an invalid file entry.")
        path = _clean_text(raw_file.get("path"))
        content = raw_file.get("content")
        if not path or not isinstance(content, str):
            raise ProjectRuntimeError(f"{agent_name} file entries require path and string content.")
        if len(content) > MAX_FILE_CHARS:
            raise ProjectRuntimeError(f"{agent_name} file {path} is too large.")
        files.append(GeneratedFile(path=path, content=content))

    return SpecialistResult(
        task_summary=_clean_text(payload.get("task_summary")) or f"{agent_name} completed its assigned task.",
        input_format=_clean_text(payload.get("input_format")),
        output_format=_clean_text(payload.get("output_format")),
        logic=_clean_text(payload.get("logic")),
        files=files,
        notes=_clean_text(payload.get("notes")),
    )


class ProjectWorkspace:
    def __init__(self, requested_name: str, reuse_existing: bool = False) -> None:
        self.name = _slugify(requested_name) or "generated-project"
        self.reuse_existing = reuse_existing
        self.project_dir = self._existing_project_dir(self.name) if reuse_existing else self._unique_project_dir(self.name)
        self.repo_intake_context = ""
        self.code_index_context = ""
        self.relationship_map_context = ""
        self.relationship_map_entries: dict[str, str] = {}
        self.relationship_map_documents: dict[str, Document] = {}
        self.relationship_map_document: Document | None = None
        self._code_index: ProjectCodeIndex | None = None
        self._code_index_dirty_files: set[str] = set()
        self._relationship_dirty_files: set[str] = set()
        self._baseline_hashes: dict[str, str] = {}
        self._baseline_captured = False
        self._lock = RLock()

    def ensure_created(self) -> None:
        self.project_dir.mkdir(parents=True, exist_ok=True)
        if not self._baseline_captured:
            self._baseline_hashes = self._snapshot_hashes() if self.reuse_existing else {}
            self._baseline_captured = True

    def write_files(self, files: list[GeneratedFile]) -> list[str]:
        self.ensure_created()
        written: list[str] = []
        for file in files:
            written.append(self.write_file(file.path, file.content))
        return written

    def write_file(self, relative_path: str, content: str) -> str:
        if len(content) > MAX_FILE_CHARS:
            raise ProjectRuntimeError(f"{relative_path} is too large.")
        with self._lock:
            destination = self._resolve_file(relative_path)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8", newline="\n")
            written = destination.relative_to(self.project_dir).as_posix()
            self._mark_project_file_dirty(written)
            return written

    def append_file(self, relative_path: str, content: str) -> str:
        if len(content) > MAX_FILE_CHARS:
            raise ProjectRuntimeError(f"{relative_path} append content is too large.")
        with self._lock:
            destination = self._resolve_file(relative_path)
            destination.parent.mkdir(parents=True, exist_ok=True)
            with destination.open("a", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            written = destination.relative_to(self.project_dir).as_posix()
            self._mark_project_file_dirty(written)
            return written

    def read_file(self, relative_path: str) -> str:
        with self._lock:
            source = self._resolve_file(relative_path)
            if not source.exists() or not source.is_file():
                raise ProjectRuntimeError(f"File not found: {relative_path}")
            content = source.read_text(encoding="utf-8")
        if len(content) > MAX_FILE_CHARS:
            raise ProjectRuntimeError(f"{relative_path} is too large to read.")
        return content

    def list_files(self) -> list[str]:
        with self._lock:
            if not self.project_dir.exists():
                return []
            return sorted(
                path.relative_to(self.project_dir).as_posix()
                for path in self.project_dir.rglob("*")
                if path.is_file()
            )

    def search_files(self, query: str, max_results: int = 8) -> list[dict[str, str]]:
        with self._lock:
            return search_project_files(self.project_dir, query, max_results=max(1, min(max_results, 20)))

    def build_code_index(self) -> ProjectCodeIndex:
        with self._lock:
            self._code_index = build_project_code_index(self.project_dir)
            self.code_index_context = self._code_index.to_prompt_context()
            self._code_index_dirty_files.clear()
            return self._code_index

    def code_index(self) -> ProjectCodeIndex:
        with self._lock:
            if self._code_index is None:
                return self.build_code_index()
            return self._code_index

    def refresh_project_documents(self, selected_files: list[str]) -> None:
        if not selected_files:
            return
        with self._lock:
            if self._code_index is None:
                self._code_index = build_project_code_index(self.project_dir)
            else:
                refresh_project_code_index_files(self._code_index, selected_files)
            self.code_index_context = self._code_index.to_prompt_context()
            self._code_index_dirty_files.difference_update(selected_files)
            self._sync_code_index_documents()

    def apply_relationship_map_update(self, update: RelationshipMapUpdate, selected_files: list[str]) -> str:
        with self._lock:
            for path in update.removed:
                self.relationship_map_entries.pop(path, None)
                self.relationship_map_documents.pop(path, None)
            for path, entry in update.entries.items():
                self.relationship_map_entries[path] = entry.summary
                self.relationship_map_documents[path] = entry.document
            self.relationship_map_context = relationship_map_context(self.relationship_map_entries)
            self.relationship_map_document = relationship_map_document(self.relationship_map_entries)
            self._relationship_dirty_files.difference_update(selected_files)
            self._sync_code_index_documents()
            return self.relationship_map_context

    def relationship_dirty_files(self) -> list[str]:
        with self._lock:
            return sorted(self._relationship_dirty_files)

    def relationship_graph(self) -> str:
        return self.relationship_map_context or "Project relationship map:\n- No relationship map is available for this workspace."

    def _mark_project_file_dirty(self, relative_path: str) -> None:
        self._code_index_dirty_files.add(relative_path)
        if self.reuse_existing:
            self._relationship_dirty_files.add(relative_path)

    def _sync_code_index_documents(self) -> None:
        if self._code_index is None:
            return
        documents = [self._code_index.file_documents[path] for path in sorted(self._code_index.file_documents)]
        documents.extend(self.relationship_map_documents[path] for path in sorted(self.relationship_map_documents))
        if self.relationship_map_document is not None:
            documents.append(self.relationship_map_document)
        self._code_index.documents = documents

    def change_summary(self) -> dict[str, list[str]]:
        with self._lock:
            current = self._snapshot_hashes()
        created = sorted(path for path in current if path not in self._baseline_hashes)
        modified = sorted(
            path
            for path, digest in current.items()
            if path in self._baseline_hashes and self._baseline_hashes[path] != digest
        )
        deleted = sorted(path for path in self._baseline_hashes if path not in current)
        return {"created": created, "modified": modified, "deleted": deleted}

    def verify(self) -> str:
        outputs: list[str] = []
        py_files = sorted(self.project_dir.rglob("*.py"))
        js_files = sorted(self.project_dir.rglob("*.js"))

        if py_files:
            outputs.append(self._run([sys.executable, "-m", "py_compile", *[str(path) for path in py_files]]))
            if (self.project_dir / "tests").exists():
                outputs.append(self._run([sys.executable, "-m", "unittest", "discover", "-s", "tests"]))
        if js_files and shutil.which("node"):
            for path in js_files:
                outputs.append(self._run(["node", "--check", str(path)]))
            if (self.project_dir / "tests").exists():
                outputs.append(self._run(["node", "--test"]))
        if not outputs:
            outputs.append("No Python or JavaScript files found for static verification.")
        return "\n\n".join(outputs)

    def _resolve_file(self, relative_path: str) -> Path:
        raw_path = str(relative_path or "").strip()
        if raw_path.startswith(("/", "\\")) or Path(raw_path).is_absolute() or re.match(r"^[a-zA-Z]:", raw_path):
            raise ProjectRuntimeError(f"Unsafe file path: {relative_path}")
        parts = [
            part
            for part in raw_path.replace("\\", "/").strip("/").split("/")
            if part and part != "."
        ]
        if not parts or any(part == ".." for part in parts):
            raise ProjectRuntimeError(f"Unsafe file path: {relative_path}")
        normalized_parts = self._strip_workspace_prefix(parts)
        if not normalized_parts or any(part == ".." for part in normalized_parts):
            raise ProjectRuntimeError(f"Unsafe file path: {relative_path}")
        normalized = "/".join(normalized_parts)
        destination = (self.project_dir / normalized).resolve()
        try:
            destination.relative_to(self.project_dir.resolve())
        except ValueError as exc:
            raise ProjectRuntimeError(f"Unsafe file path: {relative_path}") from exc
        return destination

    def _strip_workspace_prefix(self, parts: list[str]) -> list[str]:
        normalized = list(parts)
        project_names = {self.name.lower(), self.project_dir.name.lower()}
        generated_root_names = {GENERATED_ROOT.name.lower(), "generated_projects"}
        saw_generated_root = False

        changed = True
        while changed and normalized:
            changed = False
            if normalized and normalized[0].lower() in generated_root_names:
                normalized = normalized[1:]
                changed = True
                saw_generated_root = True
            if normalized and normalized[0].lower() in project_names:
                normalized = normalized[1:]
                changed = True
        if saw_generated_root and len(normalized) > 1 and self._looks_like_project_prefix(normalized[0]):
            normalized = normalized[1:]
        return normalized

    def _looks_like_project_prefix(self, segment: str) -> bool:
        candidate = segment.lower()
        if "." in candidate:
            return False
        reserved_dirs = {"app", "assets", "css", "docs", "js", "public", "scripts", "src", "static", "styles", "tests"}
        if candidate in reserved_dirs:
            return False
        project_names = {self.name.lower(), self.project_dir.name.lower()}
        return any(SequenceMatcher(None, candidate, project_name).ratio() >= 0.82 for project_name in project_names)

    def _run(self, command: list[str]) -> str:
        env = os.environ.copy()
        python_path_entries = [str(self.project_dir), str(self.project_dir / "src")]
        existing_python_path = env.get("PYTHONPATH")
        if existing_python_path:
            python_path_entries.append(existing_python_path)
        env["PYTHONPATH"] = os.pathsep.join(python_path_entries)
        result = subprocess.run(
            command,
            cwd=self.project_dir,
            env=env,
            text=True,
            capture_output=True,
            timeout=30,
            check=False,
        )
        command_text = " ".join(command)
        output = (result.stdout + result.stderr).strip()
        status = "passed" if result.returncode == 0 else f"failed ({result.returncode})"
        return f"$ {command_text}\n{status}\n{output}".strip()

    def _snapshot_hashes(self) -> dict[str, str]:
        if not self.project_dir.exists():
            return {}
        hashes: dict[str, str] = {}
        for relative_path in self.list_files():
            path = self.project_dir / relative_path
            try:
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
            except OSError:
                continue
            hashes[relative_path] = digest
        return hashes

    @staticmethod
    def _unique_project_dir(base_name: str) -> Path:
        candidate = GENERATED_ROOT / base_name
        if not candidate.exists():
            return candidate
        index = 2
        while True:
            candidate = GENERATED_ROOT / f"{base_name}-{index}"
            if not candidate.exists():
                return candidate
            index += 1

    @staticmethod
    def _existing_project_dir(base_name: str) -> Path:
        candidate = (GENERATED_ROOT / base_name).resolve()
        try:
            candidate.relative_to(GENERATED_ROOT.resolve())
        except ValueError as exc:
            raise ProjectRuntimeError(f"Unsafe project name: {base_name}") from exc
        if not candidate.is_dir():
            raise ProjectRuntimeError(f"Selected project not found: {base_name}")
        return candidate


