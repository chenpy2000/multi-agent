def _mark_done(run: Run | None, agent: Agent, emit: Emitter) -> None:
    if agent.started_at is None:
        agent.started_at = now_iso()
    agent.status = "done"
    agent.finished_at = now_iso()
    emit(Message(sender=agent.name, recipient="all", kind="agent", content=agent.output), agent)


def _start_agent(agent: Agent, emit: Emitter) -> None:
    agent.status = "running"
    agent.started_at = now_iso()
    emit(Message(sender=agent.name, recipient="Orchestrator", kind="status", content=f"Starting: {agent.task}"), agent)


def _emit_handoff(sender: Agent, recipient: Agent, content: str, emit: Emitter) -> None:
    message = Message(sender=sender.name, recipient=recipient.name, kind="handoff", content=content)
    sender.messages.append(message)
    recipient.messages.append(message)
    emit(message, sender)


